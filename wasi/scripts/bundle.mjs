// js/entry.mjs (the glue) + the guest bundle -> one flat script for Porffor (entry.js).
//   node bundle.mjs <work-dir> <guest-bundle.js>   (build-component.mjs runs it)
//
// Web globals Porffor lacks come from runtime/, injected (esbuild `inject`): a bare `URL` in the
// guest resolves to runtime/url.mjs, and what a guest never names is tree-shaken away. Code
// that reaches a global through `globalThis` (`globalThis.URL`, `typeof globalThis.fetch`)
// is not something injection rewrites, so a first pass finds those names, and the ones
// runtime/ provides are installed on globalThis before any guest code runs.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
const [outDir, guest] = process.argv.slice(2);
const aliases = JSON.parse(fs.readFileSync(path.join(outDir, 'aliases.json'), 'utf8'));
const features = JSON.parse(fs.readFileSync(path.join(outDir, 'features.json'), 'utf8'));
const lib = (name) => path.resolve(import.meta.dirname, '../../runtime', name);
const hasClock = aliases['wasi:clocks/monotonic-clock@0.3.0'] !== undefined;
const hasHttp = aliases['wasi:http/client@0.3.0'] !== undefined;
const hasEnvironment = aliases['wasi:cli/environment@0.3.0'] !== undefined;
// meshx:intl whole (include meshx:intl/imports@0.1.0): runtime/intl.mjs imports every interface
const hasIntl = ['locale', 'time-zone', 'date-time', 'number', 'plural', 'list', 'text'].every(
	(name) => aliases[`meshx:intl/${name}@0.1.0`] !== undefined
);

/** What runtime/ provides: each file, the globals it exports, and whether this world gets it. */
// Whether the guest names `subtle` (crypto.subtle): only then does it get the Web Crypto shim,
// @noble and all, in place of Porffor's own crypto. Its own code and its imports, bundled
// without the providers (a provider would name it itself), the world's imports and the
// build's other aliases left out.
const guestOnly = await build({
	entryPoints: [path.resolve(guest)],
	bundle: true,
	format: 'esm',
	platform: 'neutral',
	write: false,
	metafile: true,
	logLevel: 'silent',
	plugins: [
		{
			name: 'world-imports',
			setup(pluginBuild) {
				pluginBuild.onResolve({ filter: /^[a-z][a-z0-9-]*:/ }, (args) => ({
					path: args.path,
					external: true
				}));
				pluginBuild.onResolve({ filter: /^[\w@-]/ }, (args) =>
					args.path in aliases ? { path: args.path, external: true } : undefined
				);
			}
		}
	]
});
const usesSubtle = /\bsubtle\b/.test(guestOnly.outputFiles[0].text);
// Whether it calls `.normalize(`: only then is String.prototype.normalize (which Porffor
// lacks) installed, ahead of the guest's code (runtime/string-normalize.mjs; ASCII only for now)
const usesNormalize = /\.normalize\s*\(/.test(guestOnly.outputFiles[0].text);
// Whether it imports @noble/hashes' scrypt (better-auth hashes passwords with it): only then
// is that module pointed at runtime/scrypt.mjs, over Colin Percival's C (runtime/c/scrypt), and the
// C compiled in (natives.json, which src/build.mjs reads)
const NOBLE_SCRYPT = /[\\/]@noble[\\/]hashes[\\/](?:esm[\\/])?scrypt\.js$/;
const usesScrypt = Object.keys(guestOnly.metafile.inputs).some((input) => NOBLE_SCRYPT.test(input));

fs.writeFileSync(path.join(outDir, 'natives.json'), JSON.stringify({ scrypt: usesScrypt }));

if (usesScrypt)
	fs.writeFileSync(
		path.join(outDir, 'js', 'scrypt-native.mjs'),
		`// runtime/scrypt.mjs's way into the C (generated by bundle.mjs): crypto_scrypt over the
// Uint8Arrays' own bytes, nothing copied. 0 on success, crypto_scrypt's -1, or -2 for an
// argument that is not a Uint8Array. The JS after the C never runs; it keeps the result
// opaque to Porffor's type inference, as js/rt.mjs's functions do.
const slot = [];
export function nativeScrypt(password, salt, N, r, p, out) {
	Porffor.c\`int crypto_scrypt(const uint8_t *, size_t, const uint8_t *, size_t, uint64_t, uint32_t, uint32_t, uint8_t *, size_t);
	jsval rt_jsval(jsval v);
	jsval rt_jsnum(f64 v);
#ifndef RT_JSVAL
#define RT_JSVAL(x) _Generic((x), jsval: rt_jsval, default: rt_jsnum)(x)
#endif
// a Uint8Array's length, and its bytes (bufferPtr already includes the view's byte offset;
// the bytes start 4 past it), as runtime/c/async.c's rt_pop_bytes reads them
#ifndef RT_U8_LEN
#define RT_U8_LEN(v) ((size_t)*(u32*)(MEM + (u32)(v).val))
#define RT_U8_PTR(v) ((uint8_t*)(MEM + *(u32*)(MEM + (u32)(v).val + 4) + 4))
#endif
	const jsval pw_ = RT_JSVAL(\${password}), salt_ = RT_JSVAL(\${salt}), out_ = RT_JSVAL(\${out});
	// TYPES.uint8array
	if (porf_jv_type(pw_) != 81 || porf_jv_type(salt_) != 81 || porf_jv_type(out_) != 81) return porf_box_num(-2);
	const int rc = crypto_scrypt(RT_U8_PTR(pw_), RT_U8_LEN(pw_), RT_U8_PTR(salt_), RT_U8_LEN(salt_),
		(uint64_t)RT_JSVAL(\${N}).val, (uint32_t)RT_JSVAL(\${r}).val, (uint32_t)RT_JSVAL(\${p}).val,
		RT_U8_PTR(out_), RT_U8_LEN(out_));
	return porf_box_num((f64)rc);\`;
	slot.push(password, salt, N, r, p, out);
	return slot.pop();
}
`
	);

const PROVIDERS = [
	{ file: 'abort.mjs', names: ['AbortController', 'AbortSignal', 'DOMException'], when: true },
	{
		file: 'readable-stream.mjs',
		names: ['ReadableStream', 'ReadableStreamDefaultReader'],
		when: true
	},
	{
		file: 'writable-stream.mjs',
		names: ['WritableStream', 'WritableStreamDefaultWriter'],
		when: true
	},
	{ file: 'transform-stream.mjs', names: ['TransformStream'], when: true },
	{ file: 'text-decoder-stream.mjs', names: ['TextDecoderStream'], when: true },
	{ file: 'text-encoder-stream.mjs', names: ['TextEncoderStream'], when: true },
	{ file: 'url.mjs', names: ['URL', 'URLSearchParams'], when: true },
	{ file: 'structured-clone.mjs', names: ['structuredClone'], when: true },
	{ file: 'event-target.mjs', names: ['EventTarget'], when: true },
	{ file: 'event.mjs', names: ['Event'], when: true },
	{ file: 'custom-event.mjs', names: ['CustomEvent'], when: true },
	{ file: 'message-event.mjs', names: ['MessageEvent'], when: true },
	// both from file.mjs: File extends Blob, and esbuild orders an injected file by its
	// place among the injected, not after its imports, so blob.mjs injected on its own could
	// land after the class that extends it
	{ file: 'file.mjs', names: ['Blob', 'File'], when: true },
	// one file for all three, as file.mjs is for Blob and File
	{ file: 'crypto.mjs', names: ['crypto', 'CryptoKey', 'SubtleCrypto'], when: usesSubtle },
	{ file: 'form-data.mjs', names: ['FormData'], when: true },
	{ file: 'headers.mjs', names: ['Headers'], when: true },
	{ file: 'request.mjs', names: ['Request'], when: true },
	{ file: 'response.mjs', names: ['Response'], when: true },
	// what libraries fall back to when node:async_hooks will not import (Workers' global)
	{ file: 'async-local-storage.mjs', names: ['AsyncLocalStorage'], when: true },
	// setTimeout and friends, in a world that can wait on the monotonic clock
	{
		file: 'timers.mjs',
		names: ['setTimeout', 'setInterval', 'clearTimeout', 'clearInterval'],
		when: hasClock
	},
	// fetch and friends, in a world that can make outgoing requests
	{ file: 'fetch.mjs', names: ['fetch'], when: hasHttp },
	{ file: 'event-source.mjs', names: ['EventSource'], when: hasHttp },
	{ file: 'intl.mjs', names: ['Intl'], when: hasIntl },
	// yields need the async runtime
	{
		file: 'scheduler.mjs',
		names: [
			'scheduler',
			'setImmediate',
			'clearImmediate',
			'requestIdleCallback',
			'cancelIdleCallback'
		],
		when: features.async
	}
].filter((provider) => provider.when);

const options = {
	entryPoints: [path.join(outDir, 'js/entry.mjs')],
	bundle: true,
	format: 'esm',
	platform: 'neutral',
	alias: {
		...aliases,
		'rt-guest': path.resolve(guest),
		'rt-bridge': path.resolve(outDir, 'js/rt.mjs'),
		// what library modules import their timers and the environment from
		'wasi-porffor:timers': lib(hasClock ? 'timers.mjs' : 'no-timers.mjs'),
		'wasi-porffor:environment': lib(hasEnvironment ? 'environment.mjs' : 'no-environment.mjs'),
		...(usesScrypt
			? { 'wasi-porffor:scrypt-native': path.join(outDir, 'js', 'scrypt-native.mjs') }
			: {})
	},
	inject: [
		...(usesNormalize ? [lib('string-normalize.mjs')] : []),
		...PROVIDERS.map((provider) => lib(provider.file))
	],
	target: 'es2022',
	// Porffor has no queueMicrotask.
	banner: { js: 'function queueMicrotask(f) { Promise.resolve().then(f); }' },
	logLevel: 'warning',
	plugins: [
		// A package's "sideEffects": false is not trusted: esbuild drops the init call of a
		// module that is imported statically and also dynamically (it wraps it lazily), so the
		// static import reads its bindings before they are set. better-auth's memory adapter
		// does this. Only packages resolved here are affected: a guest Vite already bundled
		// imports nothing from node_modules.
		{
			name: 'package-side-effects',
			setup(pluginBuild) {
				pluginBuild.onResolve({ filter: /.*/ }, async (args) => {
					if (args.pluginData === 'package-side-effects') return undefined;

					const resolved = await pluginBuild.resolve(args.path, {
						kind: args.kind,
						importer: args.importer,
						resolveDir: args.resolveDir,
						with: args.with,
						pluginData: 'package-side-effects'
					});

					if (resolved.errors.length > 0 || resolved.external) return undefined;

					// @noble/hashes' scrypt, however it is imported: the C one (see usesScrypt)
					if (usesScrypt && NOBLE_SCRYPT.test(resolved.path)) return { path: lib('scrypt.mjs') };

					if (!resolved.path.includes(`${path.sep}node_modules${path.sep}`)) return undefined;

					return { ...resolved, sideEffects: true };
				});
			}
		}
	]
};

// A fetch-handler server (the world exports wasi:http/handler): the guest's default export
// ({ fetch }) becomes the handler export, through runtime/serve.mjs.
if (features.httpHandler) {
	const adapter = path.join(outDir, 'js', 'guest-http.mjs');
	const guestPath = JSON.stringify(path.resolve(guest));

	fs.writeFileSync(
		adapter,
		`// The guest as a wasi:http server (generated by bundle.mjs).\n` +
			`import app from ${guestPath};\nimport { httpHandler } from ${JSON.stringify(lib('serve.mjs'))};\n\n` +
			`export * from ${guestPath};\nexport const handler = httpHandler(app);\n`
	);
	options.alias['rt-guest'] = adapter;
}

// Pass 1: which provided globals the program reaches through globalThis.
const first = await build({ ...options, write: false });
const reached = new Set();

for (const match of first.outputFiles[0].text.matchAll(
	/\bglobalThis\s*(?:\.\s*([A-Za-z_$][\w$]*)|\[\s*(['"])([A-Za-z_$][\w$]*)\2\s*\])/g
))
	reached.add(match[1] ?? match[3]);

const installs = PROVIDERS.flatMap((provider) =>
	provider.names.filter((name) => reached.has(name)).map((name) => ({ name, file: provider.file }))
);

// Pass 2: the program, with those globals installed first (as the platform's own are:
// writable, configurable, not enumerable).
if (installs.length > 0) {
	const installer = path.join(outDir, 'js', 'globals.mjs');
	const imports = installs.map(
		({ name, file }) => `import { ${name} as ${name}$ } from ${JSON.stringify(lib(file))};`
	);
	const defines = installs.map(
		({ name }) =>
			`Object.defineProperty(globalThis, ${JSON.stringify(name)}, { value: ${name}$, writable: true, configurable: true, enumerable: false });`
	);

	fs.writeFileSync(
		installer,
		`// Globals the program reaches through globalThis (generated by bundle.mjs).\n${imports.join('\n')}\n\n${defines.join('\n')}\n`
	);
	options.inject.unshift(installer);
}
await build({ ...options, outfile: path.join(outDir, 'entry.js') });
console.log(
	'bundled ->',
	path.join(outDir, 'entry.js'),
	installs.length > 0 ? `(on globalThis: ${installs.map(({ name }) => name).join(', ')})` : ''
);
